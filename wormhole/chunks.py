MAX_TOTAL = 8 * 1024 * 1024
MAX_CHUNK = 1024 * 1024
MAX_CHUNKS = 256
BLOCK = 65536
SCENARIOS = ('healthy', 'missing', 'duplicate', 'reordered', 'truncated', 'corrupted')
TRANSPORTS = ('local', 'http-loopback')
SEED = b'WORMHOLE SYNTHETIC BINARY FIXTURE v1\x00'
SHA = {'type': 'string', 'pattern': r'^[0-9a-f]{64}$(?![\s\S])', 'minLength': 64, 'maxLength': 64}


def obj(properties):
    return {'type': 'object', 'properties': properties, 'required': list(properties), 'additionalProperties': False}


def integer(maximum, minimum=0):
    return {'type': 'integer', 'minimum': minimum, 'maximum': maximum}


MANIFEST_SCHEMA = obj({**_COMMON, 'operation': {'type': 'string', 'const': 'synthetic-chunks'},
    'synthetic': {'type': 'boolean', 'const': True},
    'input_name': {'type': 'string', 'const': 'source.synthetic.bin'},
    'total_size': integer(MAX_TOTAL, 1), 'whole_sha256': SHA,
    'chunk_size': integer(MAX_CHUNK, 1),
    'chunks': {'type': 'array', 'minItems': 1, 'maxItems': MAX_CHUNKS,
        'x-uniqueBy': ['index'], 'items': obj({'index': integer(MAX_CHUNKS - 1),
            'offset': integer(MAX_TOTAL - 1), 'size': integer(MAX_CHUNK, 1), 'sha256': SHA,
            'name': {'type': 'string', 'minLength': 16, 'maxLength': 16,
                     'pattern': r'^chunk-[0-9]{6}\.bin$(?![\s\S])'}})}})


class ChunkError(RunError):
    pass


def require(value, code='chunk_record_invalid'):
    if not value:
        raise ChunkError(code, 'Synthetic chunk operation refused; inspect its bounded component receipt.')


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()


def sha(value):
    return hashlib.sha256(value).hexdigest()


def schema():
    return deepcopy({'$schema': 'https://json-schema.org/draft/2020-12/schema',
        '$id': 'urn:jake-wormhole:schema:chunk-manifest:1.0',
        'title': 'Wormhole synthetic chunk manifest v1',
        '$comment': 'Generated by wormhole.chunks.schema(). Runtime additionally requires contiguous ordered indices/offsets, exact chunk names/sizes, and a separately bound manifest digest. Hashes establish consistency, not origin authenticity.',
        **MANIFEST_SCHEMA})


def validate_manifest(value):
    try:
        _bounded_json(value)
        _validate(MANIFEST_SCHEMA, value, '$')
    except (ValueError, TypeError, KeyError, RecursionError):
        raise ChunkError('chunk_manifest_invalid', 'The bounded synthetic chunk manifest is invalid.') from None
    count = (value['total_size'] + value['chunk_size'] - 1) // value['chunk_size']
    require(len(value['chunks']) == count, 'chunk_manifest_order')
    for index, item in enumerate(value['chunks']):
        require(item['index'] == index and item['offset'] == index * value['chunk_size'] and
            item['name'] == f'chunk-{index:06}.bin' and
            item['size'] == min(value['chunk_size'], value['total_size'] - item['offset']), 'chunk_manifest_order')
    return value


def deadline_check(deadline):
    require(time.monotonic() < deadline, 'chunk_timeout')


def ordinary(path):
    _owned(path)
    info = path.stat()
    require(stat.S_ISREG(info.st_mode) and info.st_size <= MAX_TOTAL, 'chunk_file_invalid')
    return info


def identity(info):
    return info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns


@contextmanager
def stable_file(path):
    before = ordinary(path)
    descriptor = os.open(path, os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0))
    with os.fdopen(descriptor, 'rb') as stream:
        require(identity(os.fstat(stream.fileno())) == identity(before), 'chunk_input_changed')
        yield stream
        require(identity(os.fstat(stream.fileno())) == identity(before) == identity(ordinary(path)), 'chunk_input_changed')


def file_hash(path, deadline):
    digest, size = hashlib.sha256(), 0
    with stable_file(path) as stream:
        while True:
            deadline_check(deadline)
            raw = stream.read(BLOCK)
            if not raw:
                break
            size += len(raw)
            require(size <= MAX_TOTAL, 'chunk_size_bound')
            digest.update(raw)
    return digest.hexdigest(), size


def exclusive(path):
    _owned(path.parent, directory=True)
    return os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, 'O_NOFOLLOW', 0), 0o600), 'wb')


def generate_fixture(path, size, deadline):
    require(type(size) is int and 1 <= size <= MAX_TOTAL, 'chunk_size_bound')
    pattern = hashlib.sha256(SEED).digest() * 2048
    with exclusive(path) as stream:
        remaining = size
        while remaining:
            deadline_check(deadline)
            raw = pattern[:min(remaining, len(pattern))]
            stream.write(raw)
            remaining -= len(raw)
        stream.flush(); os.fsync(stream.fileno())


def split_fixture(run, chunk_size, deadline):
    require(type(chunk_size) is int and 1 <= chunk_size <= MAX_CHUNK, 'chunk_size_bound')
    source = run.file('private/chunks/source.synthetic.bin')
    total = ordinary(source).st_size
    require(1 <= total <= MAX_TOTAL and (total + chunk_size - 1) // chunk_size <= MAX_CHUNKS, 'chunk_count_bound')
    directory = run.file('private/chunks/parts'); directory.mkdir(mode=0o700)
    chunks, whole = [], hashlib.sha256()
    with stable_file(source) as stream:
        offset = 0
        while offset < total:
            deadline_check(deadline)
            name, digest, size = f'chunk-{len(chunks):06}.bin', hashlib.sha256(), min(chunk_size, total - offset)
            with exclusive(directory / name) as output:
                remaining = size
                while remaining:
                    deadline_check(deadline)
                    raw = stream.read(min(BLOCK, remaining))
                    require(raw, 'chunk_input_changed')
                    output.write(raw); whole.update(raw); digest.update(raw); remaining -= len(raw)
                output.flush(); os.fsync(output.fileno())
            chunks.append({'index': len(chunks), 'offset': offset, 'size': size, 'sha256': digest.hexdigest(), 'name': name})
            offset += size
        require(not stream.read(1), 'chunk_input_changed')
    return validate_manifest({**common(run.manifest()), 'operation': 'synthetic-chunks', 'synthetic': True,
        'input_name': 'source.synthetic.bin', 'total_size': total, 'whole_sha256': whole.hexdigest(),
        'chunk_size': chunk_size, 'chunks': chunks})


class LocalChunks:
    """Private fixed-directory adapter. No imported paths or fallback source."""
    def __init__(self, directory):
        self.directory = Path(directory)

    def validate_set(self, names):
        _owned(self.directory, directory=True)
        require(set(os.listdir(self.directory)) == set(names), 'chunk_set_mismatch')
        for name in names:
            require(re.fullmatch(r'chunk-[0-9]{6}\.bin', name), 'chunk_name_invalid')
            ordinary(self.directory / name)

    @contextmanager
    def open(self, item, deadline):
        deadline_check(deadline)
        with stable_file(self.directory / item['name']) as stream:
            yield stream.read


class LoopbackFixture:
    """One local fixture server with a fixed allowlist and bounded lifetime."""
    def __init__(self, local, names, deadline):
        local.validate_set(names)
        self.local, self.names, self.deadline = local, set(names), deadline
        fixture = self
        class Handler(BaseHTTPRequestHandler):
            protocol_version = 'HTTP/1.0'
            def log_message(self, *_):
                pass
            def do_GET(self):
                self.connection.settimeout(max(.01, min(.5, fixture.deadline - time.monotonic())))
                if self.path not in {'/' + name for name in fixture.names}:
                    self.send_error(404); return
                try:
                    path = fixture.local.directory / self.path[1:]
                    with stable_file(path) as stream:
                        size = ordinary(path).st_size
                        require(size <= MAX_CHUNK, 'chunk_size_bound')
                        self.send_response(200)
                        self.send_header('Content-Length', str(size))
                        self.send_header('Content-Type', 'application/octet-stream')
                        self.end_headers()
                        while True:
                            deadline_check(fixture.deadline)
                            raw = stream.read(BLOCK)
                            if not raw: break
                            self.wfile.write(raw)
                except (OSError, RunError):
                    self.close_connection = True
        self.server = HTTPServer(('127.0.0.1', 0), Handler)
        self.thread = threading.Thread(target=self.server.serve_forever, kwargs={'poll_interval': .02}, daemon=True)

    def __enter__(self):
        self.thread.start()
        return self

    def __exit__(self, *_):
        self.server.shutdown(); self.server.server_close(); self.thread.join(timeout=1)
        require(not self.thread.is_alive(), 'chunk_http_shutdown')

    def validate_set(self, names):
        require(set(names) == self.names, 'chunk_set_mismatch')
        self.local.validate_set(names)

    @contextmanager
    def open(self, item, deadline):
        deadline_check(deadline)
        require(item['name'] in self.names, 'chunk_name_invalid')
        connection = http.client.HTTPConnection('127.0.0.1', self.server.server_port,
            timeout=max(.01, min(.5, deadline - time.monotonic())))
        try:
            connection.request('GET', '/' + item['name'], headers={'Connection': 'close'})
            response = connection.getresponse()
            lengths = [value for key, value in response.getheaders() if key.lower() == 'content-length']
            require(response.status == 200 and lengths == [str(item['size'])] and
                response.getheader('Transfer-Encoding') is None and response.getheader('Content-Type') == 'application/octet-stream',
                'chunk_http_response')
            def bounded_read(maximum):
                deadline_check(deadline)
                # read1 performs one underlying receive, so a dripping response
                # cannot reset an aggregate read(n) timeout indefinitely.
                if connection.sock is not None:
                    connection.sock.settimeout(max(.001, min(.5, deadline - time.monotonic())))
                raw = response.read1(maximum)
                deadline_check(deadline)
                return raw
            yield bounded_read
        except (OSError, http.client.HTTPException):
            raise ChunkError('chunk_http_transport', 'The bounded loopback fixture did not complete.') from None
        finally:
            connection.close()


