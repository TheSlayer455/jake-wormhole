def reconstruct(run, manifest, expected_manifest_sha256, transport, deadline, checked):
    validate_manifest(manifest)
    require(sha(canonical(manifest)) == expected_manifest_sha256, 'chunk_manifest_identity')
    require(common(run.manifest()) == {key: manifest[key] for key in _COMMON}, 'chunk_run_identity')
    transport.validate_set([item['name'] for item in manifest['chunks']])
    output, partial = run.file('private/chunks/reconstructed.synthetic.bin'), run.file('private/chunks/.reconstructed.partial')
    require(not output.exists() and not output.is_symlink(), 'chunk_output_exists')
    whole, total, created = hashlib.sha256(), 0, False
    try:
        with exclusive(partial) as stream:
            created = True
            for item in manifest['chunks']:
                digest, size = hashlib.sha256(), 0
                with transport.open(item, deadline) as read:
                    while True:
                        deadline_check(deadline)
                        raw = read(min(BLOCK, item['size'] + 1 - size))
                        if not raw: break
                        size += len(raw)
                        require(size <= item['size'], 'chunk_size_mismatch')
                        stream.write(raw); digest.update(raw); whole.update(raw); total += len(raw)
                require(size == item['size'], 'chunk_size_mismatch')
                require(digest.hexdigest() == item['sha256'], 'chunk_hash_mismatch')
                checked.append({'index': item['index'], 'size': size, 'sha256': digest.hexdigest()})
            require(total == manifest['total_size'], 'chunk_total_mismatch')
            require(whole.hexdigest() == manifest['whole_sha256'], 'chunk_whole_mismatch')
            deadline_check(deadline)
            stream.flush(); os.fsync(stream.fileno())
        require(not output.exists() and not output.is_symlink(), 'chunk_output_exists')
        require(source_identity() == (manifest['source_revision'], False), 'chunk_source_changed')
        deadline_check(deadline)
        os.replace(partial, output)
        return {'path': 'private/chunks/reconstructed.synthetic.bin', 'size': total, 'sha256': whole.hexdigest()}
    finally:
        if created and partial.exists():
            ordinary(partial); partial.unlink()


def inject_fault(run, manifest, scenario):
    parts = run.file('private/chunks/parts')
    if scenario == 'missing':
        (parts / manifest['chunks'][0]['name']).unlink()
    elif scenario == 'duplicate':
        manifest['chunks'].append(deepcopy(manifest['chunks'][0]))
    elif scenario == 'reordered':
        require(len(manifest['chunks']) >= 2, 'chunk_fault_unavailable')
        manifest['chunks'][0], manifest['chunks'][1] = manifest['chunks'][1], manifest['chunks'][0]
    elif scenario in {'truncated', 'corrupted'}:
        path = parts / manifest['chunks'][0]['name']
        with path.open('r+b') as stream:
            if scenario == 'truncated': stream.truncate(manifest['chunks'][0]['size'] - 1)
            else:
                byte = stream.read(1); stream.seek(0); stream.write(bytes([byte[0] ^ 1]))


def execute_fixture(run, *, transport='local', scenario='healthy', size=262181, chunk_size=65536, timeout=15):
    """Own the Run lock; one attempt only. Return failed component data, not acceptance."""
    require(transport in TRANSPORTS and scenario in SCENARIOS and type(size) is int and 2 <= size <= MAX_TOTAL and
        type(chunk_size) is int and 1 <= chunk_size <= MAX_CHUNK and
        2 <= (size + chunk_size - 1) // chunk_size <= MAX_CHUNKS and
        type(timeout) in (int, float) and .05 <= timeout <= 30, 'chunk_configuration')
    with run.locked():
        base = common(run.manifest())
        require(base['mode'] == 'container-reference' and source_identity() == (base['source_revision'], False) and
                base['source_dirty'] is False, 'chunk_source_changed')
        require(not run.file('evidence/chunks.json').exists() and not run.file('private/chunks').exists(), 'chunk_attempt_exists')
        began, deadline = time.monotonic(), time.monotonic() + timeout
        run.file('private/chunks').mkdir(mode=0o700)
        plan = {**base, 'operation': 'synthetic-chunks', 'synthetic': True, 'scenario': scenario, 'transport': transport,
            'fixture': 'wormhole-generated-binary-v1', 'size': size, 'chunk_size': chunk_size, 'timeout_seconds': timeout,
            'runtime_pipeline_complete': False, 'reference_eligible': False, 'production_iso_eligible': False}
        atomic_json(run.file('evidence/chunk-plan.json'), plan)
        receipt = {**base, 'operation': 'synthetic-chunks', 'synthetic': True, 'status': 'pending',
            'plan_sha256': sha(canonical(plan)), 'manifest_sha256': None, 'checked_chunks': [], 'verified_output': None,
            'failure': None, 'duration_seconds': 0., 'updated_at': now(), 'runtime_pipeline_complete': False,
            'reference_eligible': False, 'production_iso_eligible': False}
        atomic_json(run.file('evidence/chunks.json'), receipt)
        try:
            generate_fixture(run.file('private/chunks/source.synthetic.bin'), size, deadline)
            manifest = split_fixture(run, chunk_size, deadline)
            atomic_json(run.file('evidence/chunk-original-manifest.json'), manifest)
            receipt['manifest_sha256'] = sha(canonical(manifest))
            inject_fault(run, manifest, scenario)
            atomic_json(run.file('evidence/chunk-manifest.json'), manifest)
            local = LocalChunks(run.file('private/chunks/parts'))
            if transport == 'http-loopback':
                with LoopbackFixture(local, [item['name'] for item in manifest['chunks']], deadline) as adapter:
                    result = reconstruct(run, manifest, receipt['manifest_sha256'], adapter, deadline, receipt['checked_chunks'])
            else:
                result = reconstruct(run, manifest, receipt['manifest_sha256'], local, deadline, receipt['checked_chunks'])
            require(source_identity() == (base['source_revision'], False), 'chunk_source_changed')
            deadline_check(deadline)
            receipt.update(status='passed', verified_output=result)
        except (RunError, OSError, ValueError) as error:
            receipt.update(status='failed', failure={'code': getattr(error, 'code', 'chunk_io_error'), 'recorded_at': now()})
        receipt.update(duration_seconds=time.monotonic() - began, updated_at=now())
        atomic_json(run.file('evidence/chunks.json'), receipt)
        return receipt


def report_chunks(run):
    """Validate this component only; never assert complete pipeline eligibility."""
    base, plan, receipt = common(run.manifest()), read_json(run.file('evidence/chunk-plan.json')), read_json(run.file('evidence/chunks.json'))
    validate_records(plan, receipt)
    require(all({key: record[key] for key in _COMMON} == base for record in (plan, receipt)), 'chunk_run_identity')
    require(plan['operation'] == receipt['operation'] == 'synthetic-chunks' and plan['synthetic'] is receipt['synthetic'] is True and
        receipt['plan_sha256'] == sha(canonical(plan)) and receipt['status'] in {'pending', 'passed', 'failed'} and
        all(record[key] is False for record in (plan, receipt) for key in
            ('runtime_pipeline_complete', 'reference_eligible', 'production_iso_eligible')), 'chunk_record_invalid')
    if receipt['status'] == 'passed':
        manifest = validate_manifest(read_json(run.file('evidence/chunk-original-manifest.json')))
        require({key: manifest[key] for key in _COMMON} == base and
            (manifest['total_size'], manifest['chunk_size']) == (plan['size'], plan['chunk_size']) and
            receipt['failure'] is None and receipt['manifest_sha256'] == sha(canonical(manifest)) ==
            sha(canonical(read_json(run.file('evidence/chunk-manifest.json')))), 'chunk_manifest_identity')
        digest, size = file_hash(run.file('private/chunks/reconstructed.synthetic.bin'), time.monotonic() + 10)
        require(file_hash(run.file('private/chunks/source.synthetic.bin'), time.monotonic() + 10) == (digest, size), 'chunk_input_changed')
        require(receipt['verified_output'] == {'path': 'private/chunks/reconstructed.synthetic.bin', 'size': size, 'sha256': digest} and
            (digest, size) == (manifest['whole_sha256'], manifest['total_size']) and receipt['checked_chunks'] ==
            [{key: item[key] for key in ('index', 'size', 'sha256')} for item in manifest['chunks']], 'chunk_output_changed')
    else:
        require(receipt['verified_output'] is None, 'chunk_record_invalid')
    return {'plan': plan, 'result': receipt, 'text': f"WORMHOLE SYNTHETIC CHUNKS\nStatus: {receipt['status']}\nTransport: {plan['transport']}\nScenario: {plan['scenario']}\nProduction ISO eligible: false\n"}


def validate_records(plan, receipt):
    plan_fields = set(_COMMON) | {'operation', 'synthetic', 'scenario', 'transport', 'fixture', 'size', 'chunk_size',
        'timeout_seconds', 'runtime_pipeline_complete', 'reference_eligible', 'production_iso_eligible'}
    receipt_fields = set(_COMMON) | {'operation', 'synthetic', 'status', 'plan_sha256', 'manifest_sha256', 'checked_chunks',
        'verified_output', 'failure', 'duration_seconds', 'updated_at', 'runtime_pipeline_complete',
        'reference_eligible', 'production_iso_eligible'}
    require(type(plan) is dict and set(plan) == plan_fields and type(receipt) is dict and set(receipt) == receipt_fields)
    try:
        for record in (plan, receipt):
            _bounded_json(record)
            _validate(obj(_COMMON), {key: record[key] for key in _COMMON}, '$')
    except (ValueError, TypeError, KeyError, RecursionError):
        raise ChunkError('chunk_record_invalid', 'A bounded chunk component record is invalid.') from None
    require(plan['scenario'] in SCENARIOS and plan['transport'] in TRANSPORTS and
        plan['fixture'] == 'wormhole-generated-binary-v1' and type(plan['size']) is int and 2 <= plan['size'] <= MAX_TOTAL and
        type(plan['chunk_size']) is int and 1 <= plan['chunk_size'] <= MAX_CHUNK and
        2 <= (plan['size'] + plan['chunk_size'] - 1) // plan['chunk_size'] <= MAX_CHUNKS and
        type(plan['timeout_seconds']) in (int, float) and math.isfinite(plan['timeout_seconds']) and
        .05 <= plan['timeout_seconds'] <= 30 and type(receipt['status']) is str and receipt['status'] in {'pending', 'passed', 'failed'} and
        type(receipt['plan_sha256']) is str and re.fullmatch('[a-f0-9]{64}', receipt['plan_sha256']) and
        (receipt['manifest_sha256'] is None or type(receipt['manifest_sha256']) is str and re.fullmatch('[a-f0-9]{64}', receipt['manifest_sha256'])) and
        type(receipt['duration_seconds']) in (int, float) and math.isfinite(receipt['duration_seconds']) and
        receipt['duration_seconds'] >= 0 and type(receipt['updated_at']) is str and len(receipt['updated_at']) <= 32 and
        type(receipt['checked_chunks']) is list and len(receipt['checked_chunks']) <= MAX_CHUNKS)
    for index, item in enumerate(receipt['checked_chunks']):
        require(type(item) is dict and set(item) == {'index', 'size', 'sha256'} and type(item['index']) is int and
            item['index'] == index and type(item['size']) is int and 1 <= item['size'] <= MAX_CHUNK and
            type(item['sha256']) is str and re.fullmatch('[a-f0-9]{64}', item['sha256']))
    failure = receipt['failure']
    require((receipt['status'] == 'failed' and type(failure) is dict and set(failure) == {'code', 'recorded_at'} and
        type(failure['code']) is str and re.fullmatch('[a-z][a-z0-9_]{0,63}', failure['code']) and
        type(failure['recorded_at']) is str and len(failure['recorded_at']) <= 32) or
        (receipt['status'] != 'failed' and failure is None))
    output = receipt['verified_output']
    require((receipt['status'] == 'passed' and type(output) is dict and set(output) == {'path', 'size', 'sha256'} and
        output['path'] == 'private/chunks/reconstructed.synthetic.bin' and type(output['size']) is int and
        1 <= output['size'] <= MAX_TOTAL and type(output['sha256']) is str and re.fullmatch('[a-f0-9]{64}', output['sha256'])) or
        (receipt['status'] != 'passed' and output is None))


def verified_source(run):
    """Future candidate boundary: a mere pathname or partial output is insufficient."""
    result = report_chunks(run)['result']
    require(result['status'] == 'passed', 'chunk_not_verified')
    return run.file(result['verified_output']['path'])


def acceptance(workspace):
    """Execute all twelve actual generated/local HTTP fixture cases serially."""
    revision = source_identity()
    require(revision[1] is False, 'chunk_source_changed')
    suite = create_run(workspace, fixture=False, kernel_lock=sys.platform.startswith('linux'))
    cases = []
    with suite.locked():
        for transport in TRANSPORTS:
            for scenario in SCENARIOS:
                require(source_identity() == revision, 'chunk_source_changed')
                run = create_run(workspace, fixture=False, kernel_lock=sys.platform.startswith('linux'))
                result = execute_fixture(run, transport=transport, scenario=scenario)
                report = report_chunks(run)
                expected = {'missing': 'chunk_set_mismatch', 'duplicate': 'chunk_manifest_invalid',
                    'reordered': 'chunk_manifest_order', 'truncated': 'chunk_http_response' if transport == 'http-loopback' else 'chunk_size_mismatch',
                    'corrupted': 'chunk_hash_mismatch'}
                if scenario == 'healthy':
                    require(result['status'] == 'passed' and verified_source(run).is_file(), 'chunk_acceptance_failed')
                    require(file_hash(run.file('private/chunks/source.synthetic.bin'), time.monotonic() + 10) ==
                        file_hash(verified_source(run), time.monotonic() + 10), 'chunk_acceptance_failed')
                else:
                    require(result['status'] == 'failed' and result['failure']['code'] == expected[scenario] and
                        not run.file('private/chunks/reconstructed.synthetic.bin').exists(), 'chunk_acceptance_failed')
                    try:
                        verified_source(run)
                    except ChunkError as error:
                        require(error.code == 'chunk_not_verified', 'chunk_acceptance_failed')
                    else:
                        require(False, 'chunk_acceptance_failed')
                require(report['result'] == result and source_identity() == revision, 'chunk_acceptance_failed')
                cases.append({'run_id': run.id, 'transport': transport, 'scenario': scenario,
                    'acceptance_status': 'passed', 'operation_status': result['status'],
                    'failure_code': None if result['failure'] is None else result['failure']['code'],
                    'manifest_sha256': result['manifest_sha256'], 'duration_seconds': result['duration_seconds']})
        value = {**common(suite.manifest()), 'operation': 'synthetic-chunk-acceptance', 'status': 'passed',
            'synthetic': True, 'cases': cases, 'runtime_pipeline_complete': False,
            'reference_eligible': False, 'production_iso_eligible': False}
        require(len(cases) == 12 and len({item['run_id'] for item in cases}) == 12, 'chunk_acceptance_failed')
        atomic_json(suite.file('evidence/chunk-acceptance.json'), value)
        return value


def main(arguments=None):
    parser = argparse.ArgumentParser(description='Independent synthetic chunk operation; no Docker, ISO or publication.')
    parser.add_argument('--workspace', required=True)
    parser.add_argument('--transport', choices=TRANSPORTS, default='local')
    parser.add_argument('--scenario', choices=SCENARIOS, default='healthy')
    parser.add_argument('--size', type=int, default=262181)
    parser.add_argument('--chunk-size', type=int, default=65536)
    parser.add_argument('--acceptance', action='store_true', help='Twelve fresh synthetic local/HTTP fixture cases; no Docker.')
    options = parser.parse_args(arguments)
    try:
        if options.acceptance:
            print(json.dumps(acceptance(options.workspace), sort_keys=True))
            return 0
        run = create_run(options.workspace, fixture=False, kernel_lock=sys.platform.startswith('linux'))
        result = execute_fixture(run, transport=options.transport, scenario=options.scenario, size=options.size, chunk_size=options.chunk_size)
        print(json.dumps({'run_id': run.id, 'component': report_chunks(run)}, sort_keys=True))
        return 0 if result['status'] == 'passed' else 1
    except (RunError, OSError, ValueError):
        print(json.dumps({'error': {'code': 'chunk_operation_refused'}}))
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
